static void Encoder_ServicePendingSpi1Dma(void)
{
  uint8_t idx;

  if (g_spi1_dma_owner != NULL)
  {
    return;
  }

  for (idx = 0u; idx < 2u; idx++)
  {
    uint8_t slot = (uint8_t)((g_spi1_dma_rr_next + idx) & 0x01u);
    MT6826_HandleTypeDef *candidate = (slot == 0u) ? &hencoder1 : &hencoder2;

    if ((candidate->read_pending != 0u) && (candidate->dma_done != 0u))
    {
      g_spi1_dma_owner = candidate;
      g_spi1_dma_rr_next = (uint8_t)((slot + 1u) & 0x01u);
      MT6826_StartDMARead(candidate);
      return;
    }
  }
}

static void Encoder_RequestRead(MT6826_HandleTypeDef *hencoder)
{
  if ((hencoder == NULL) || (hencoder->read_pending != 0u) || (hencoder->dma_done == 0u))
  {
    return;
  }

  hencoder->read_pending = 1u;
  Encoder_ServicePendingSpi1Dma();
}
